from typing import Any, Iterable, Sequence

from loguru import logger

JointVector = Sequence[float]
PoseVector = Sequence[float]

ABSOLUTE_MOVE = 0
NON_BLOCKING_MOVE = False
SERVO_BASE_PERIOD_S = 0.008
DEFAULT_HOLD_CYCLES = 2
DEFAULT_JOINT_MOVE_SPEED_RAD_S = 7.0
DEFAULT_JOINT_MOVE_ACC_RAD_S2 = 5.0
DEFAULT_JOINT_MOVE_TOL_RAD = 0.0

ROBOT_STATUS_POWERED_ON = 2
ROBOT_STATUS_ENABLED = 3
ROBOT_STATUS_CARTESIAN_POSE = 18
ROBOT_STATUS_JOINTS = 19
MOTION_STATUS_READY = 6
READY_STATUS = 0

_JKRC_MODULE: ModuleType | None = None
_JKRC_RUNTIME_HANDLE: Any | None = None
_JKRC_DLL_DIRECTORY_HANDLE: Any | None = None
_JKRC_LOAD_LOCK = threading.Lock()


class JakaError(RuntimeError):
    """Raised when the JAKA SDK returns a non-zero error code."""


@dataclass(frozen=True)
class ServoTrajectoryPlan:
    """Sent joint samples and timing metadata."""

    samples: list[list[float]]
    duration_s: float
    period_s: float
    action: str
    late_cycles: int = 0


@dataclass
class _ServoJob:
    action: str
    samples: list[list[float]] | None
    done: threading.Event
    speed_rad_s: float | None = None
    acc_rad_s2: float | None = None
    tol_rad: float = DEFAULT_JOINT_MOVE_TOL_RAD
    result: ServoTrajectoryPlan | None = None
    error: BaseException | None = None
    sample_iter: Iterable[JointVector] | None = None


class ServoQueueHandle:
    """Handle returned for queued JAKA motion jobs."""

    def __init__(self, job: _ServoJob) -> None:
        self._job = job

    def wait(self, timeout_s: float | None = None) -> ServoTrajectoryPlan:
        if not self._job.done.wait(timeout_s):
            raise TimeoutError(f"{self._job.action} job timed out")
        if self._job.error is not None:
            raise self._job.error
        if self._job.result is None:
            raise JakaError(f"{self._job.action} job finished without result")
        return self._job.result


class JakaServoRobot:
    """JAKA joint controller with a daemon sender thread.

    The control layer does not plan geometry or add start poses. Callers pass
    preplanned 125Hz samples generated by trajectory planning.
    """

    allow_legacy_singularity_search = False

    def __init__(
        self,
        ip: str,
        motion_timeout_s: float | None = None,
        sdk_module: Any | None = None,
        *,
        servo_period_s: float = SERVO_BASE_PERIOD_S,
        servo_step_num: int | None = None,
        hold_cycles: int = DEFAULT_HOLD_CYCLES,
    ) -> None:
        self.ip = ip
        self.motion_timeout_s = motion_timeout_s
        self._sdk = sdk_module or _load_jkrc()
        self.robot = self._sdk.RC(ip)

        if servo_step_num is None:
            servo_step_num = max(
                1, int(round(float(servo_period_s) / SERVO_BASE_PERIOD_S))
            )
        self.servo_step_num = max(1, int(servo_step_num))
        self.servo_period_s = SERVO_BASE_PERIOD_S * self.servo_step_num
        self.hold_cycles = max(0, int(hold_cycles))

        self._connected = False
        self._servo_enabled = False
        self._servo_j_accepts_step_num: bool | None = None
        self._servo_accepts_step_num: bool | None = None
        self._sdk_lock = threading.RLock()
        self._job_queue: queue.Queue[_ServoJob | None] = queue.Queue()
        self._shutdown_event = threading.Event()
        self._abort_current = threading.Event()
        self._worker_thread: threading.Thread | None = None

        logger.info(
            "JakaServoRobot initialized: "
            f"ip={ip}, servo_period={self.servo_period_s:.3f}s"
        )

    def connect(
        self,
        retries: int = 3,
        retry_interval_s: float = 2.0,
        power_on: bool = True,
        enable: bool = True,
    ) -> bool:
        """Login, optionally power on and enable the robot."""

        for attempt in range(1, retries + 1):
            with self._sdk_lock:
                ret = self.robot.login()
            if self._ok(ret):
                self._connected = True
                if power_on or enable:
                    self._ensure_ready(power_on=power_on, enable=enable)
                self._start_worker()
                return True

            logger.warning(f"JAKA login failed ({attempt}/{retries}): {ret}")
            time.sleep(retry_interval_s)

        logger.error("Failed to connect to JAKA robot after maximum retries")
        return False

    def close(self) -> None:
        self._abort_current.set()
        self._drain_pending_jobs(JakaError("JAKA joint controller closed"))
        self._shutdown_event.set()
        if self._worker_thread is not None and self._worker_thread.is_alive():
            self._job_queue.put(None)
            self._worker_thread.join(timeout=2.0)

        with self._sdk_lock:
            self._disable_servo_locked()
            if self._connected:
                ret = self.robot.logout()
                if not self._ok(ret):
                    logger.warning(f"JAKA logout returned: {ret}")
                self._connected = False

    def start(self) -> bool:
        if not self._connected:
            return self.connect()
        self._ensure_ready(power_on=True, enable=True)
        self._start_worker()
        return True

    def stop(self) -> None:
        self._abort_current.set()
        self._drain_pending_jobs(JakaError("JAKA joint job aborted"))
        if not self._connected:
            return

        with self._sdk_lock:
            self._disable_servo_locked()
            status = self.get_status()
            ret = self.robot.motion_abort()
            if not self._ok(ret):
                logger.warning(f"motion_abort returned: {ret}")

            if status[ROBOT_STATUS_ENABLED] == 1:
                self._require_ok(self.robot.disable_robot(), "disable_robot")
                self._wait_for_robot_status(ROBOT_STATUS_ENABLED, 0)

            if status[ROBOT_STATUS_POWERED_ON] == 1:
                self._require_ok(self.robot.power_off(), "power_off")
                self._wait_for_robot_status(ROBOT_STATUS_POWERED_ON, 0)

    def abort_motion(self) -> None:
        if not self._connected:
            return
        with self._sdk_lock:
            ret = self.robot.motion_abort()
        if not self._ok(ret):
            logger.warning(f"motion_abort returned: {ret}")

    def enqueue_joint_path(
        self,
        samples: Sequence[JointVector],
        *,
        speed_rad_s: float | None = None,
        acc_rad_s2: float | None = None,
        tol_rad: float = DEFAULT_JOINT_MOVE_TOL_RAD,
    ) -> ServoQueueHandle:
        rows = [_as_float_vector(sample, 6, "joint sample") for sample in samples]
        if not rows:
            raise ValueError("joint path must contain at least one sample")
        speed, acc, tol = _resolve_joint_move_command_limits(
            speed_rad_s,
            acc_rad_s2,
            tol_rad,
        )
        return self._enqueue("servo_j", rows, speed, acc, tol)

    def enqueue_joint_stream(
        self,
        samples: Iterable[JointVector],
        *,
        speed_rad_s: float | None = None,
        acc_rad_s2: float | None = None,
        tol_rad: float = DEFAULT_JOINT_MOVE_TOL_RAD,
    ) -> ServoQueueHandle:
        speed, acc, tol = _resolve_joint_move_command_limits(
            speed_rad_s,
            acc_rad_s2,
            tol_rad,
        )
        return self._enqueue_stream("servo_j", samples, speed, acc, tol)

    def enqueue_pose_path(self, samples: Sequence[PoseVector]) -> ServoQueueHandle:
        rows = [
            _normalize_cartesian_pose(_as_float_vector(sample, 6, "pose sample"))
            for sample in samples
        ]
        if not rows:
            raise ValueError("pose path must contain at least one sample")
        return self._enqueue("servo_p", rows)

    def move_joint_path(
        self,
        samples: Sequence[JointVector],
        *,
        speed_rad_s: float | None = None,
        acc_rad_s2: float | None = None,
        tol_rad: float = DEFAULT_JOINT_MOVE_TOL_RAD,
        wait: bool = True,
        timeout_s: float | None = None,
    ) -> ServoTrajectoryPlan | ServoQueueHandle:
        handle = self.enqueue_joint_path(
            samples,
            speed_rad_s=speed_rad_s,
            acc_rad_s2=acc_rad_s2,
            tol_rad=tol_rad,
        )
        return handle.wait(timeout_s) if wait else handle

    def move_joint_stream(
        self,
        samples: Iterable[JointVector],
        *,
        speed_rad_s: float | None = None,
        acc_rad_s2: float | None = None,
        tol_rad: float = DEFAULT_JOINT_MOVE_TOL_RAD,
        wait: bool = True,
        timeout_s: float | None = None,
    ) -> ServoTrajectoryPlan | ServoQueueHandle:
        handle = self.enqueue_joint_stream(
            samples,
            speed_rad_s=speed_rad_s,
            acc_rad_s2=acc_rad_s2,
            tol_rad=tol_rad,
        )
        return handle.wait(timeout_s) if wait else handle

    def move_pose_path(
        self,
        samples: Sequence[PoseVector],
        speed_mm_s: float | None = None,
        acc_mm_s2: float | None = None,
        *,
        wait: bool = True,
        timeout_s: float | None = None,
    ) -> ServoTrajectoryPlan | ServoQueueHandle:
        if speed_mm_s is not None or acc_mm_s2 is not None:
            logger.debug(
                "move_pose_path speed/acc arguments are ignored; "
                "servo samples must be preplanned"
            )
        handle = self.enqueue_pose_path(samples)
        return handle.wait(timeout_s) if wait else handle

    def move_joint(
        self,
        joints: JointVector,
        speed: float,
        acc: float,
        blend_radius: float = DEFAULT_JOINT_MOVE_TOL_RAD,
        *,
        tol: float | None = None,
        block: bool = NON_BLOCKING_MOVE,
    ) -> None:
        row = _as_float_vector(joints, 6, "joint target")
        speed = _positive_float(speed, "joint move speed")
        acc = _positive_float(acc, "joint move acceleration")
        move_tol = blend_radius if tol is None else tol
        move_tol = _non_negative_float(move_tol, "joint move tolerance")
        with self._sdk_lock:
            ret = self._joint_move_locked(
                row,
                speed,
                acc,
                move_tol,
                block=block,
            )
        self._require_ok(ret, "move_joint")

    def move_line(
        self,
        pose: PoseVector,
        speed: float,
        acc: float,
        blend_radius: float = 0.0,
        duration: float = 0.0,
    ) -> None:
        del pose, speed, acc, blend_radius, duration
        raise RuntimeError(
            "JakaServoRobot.move_line no longer plans in the control layer; "
            "use move_pose_path with preplanned servo samples"
        )

    def get_joint_position(self) -> list[float]:
        status = self.get_status()
        return list(status[ROBOT_STATUS_JOINTS])

    def get_cartesian_position(self) -> list[float]:
        status = self.get_status()
        return list(status[ROBOT_STATUS_CARTESIAN_POSE])

    def get_status(self) -> Any:
        with self._sdk_lock:
            ret = self.robot.get_robot_status()
        self._require_ok(ret, "get_robot_status")
        return ret[1]

    def set_speed(self, ratio: float) -> None:
        ratio = float(max(0.01, min(1.0, ratio)))
        with self._sdk_lock:
            ret = self.robot.set_rapidrate(ratio)
        self._require_ok(ret, "set_rapidrate")

    def ready_for_motion(self, timeout_s: float | None = None) -> bool:
        timeout_s = self.motion_timeout_s if timeout_s is None else timeout_s
        start = time.monotonic()

        while True:
            with self._sdk_lock:
                ret = self.robot.get_motion_status()
            self._require_ok(ret, "get_motion_status")
            status = ret[1][MOTION_STATUS_READY]
            if status == READY_STATUS:
                return True
            if timeout_s is not None and time.monotonic() - start > timeout_s:
                raise TimeoutError(f"JAKA motion did not become ready in {timeout_s}s")
            time.sleep(0.01)

    def forward_kinematics(self, joint_angles: JointVector) -> list[float]:
        joints = _as_float_vector(joint_angles, 6, "joint_angles")
        if not all(math.isfinite(value) for value in joints):
            raise ValueError("joint_angles must contain finite values")
        with self._sdk_lock:
            ret = self.robot.kine_forward(joints)
        self._require_ok(ret, "kine_forward")
        return list(ret[1])

    def forword_kinematics(self, joint_angles: JointVector) -> list[float]:
        """Backward-compatible typo alias."""

        return self.forward_kinematics(joint_angles)

    def inverse_kinematics(
        self,
        cur_joint_angles: JointVector,
        target_pose: PoseVector,
    ) -> list[float]:
        seed_joints = _as_float_vector(cur_joint_angles, 6, "cur_joint_angles")
        pose = _normalize_cartesian_pose(
            _as_float_vector(target_pose, 6, "target_pose")
        )
        if not all(math.isfinite(value) for value in seed_joints + pose):
            raise ValueError("inverse_kinematics inputs must contain finite values")
        with self._sdk_lock:
            ret = self.robot.kine_inverse(
                seed_joints,
                pose,
            )
        self._require_ok(ret, "kine_inverse")
        return list(ret[1])

    def rpy_to_quaternion(self, rpy: Sequence[float]) -> Any:
        with self._sdk_lock:
            ret = self.robot.rpy_to_rot_matrix(list(rpy))
            self._require_ok(ret, "rpy_to_rot_matrix")
            ret = self.robot.rot_matrix_to_quaternion(ret[1])
        self._require_ok(ret, "rot_matrix_to_quaternion")
        return ret[1]

    def quaternion_to_rpy(self, quaternion: Sequence[float]) -> Any:
        with self._sdk_lock:
            ret = self.robot.quaternion_to_rot_matrix(list(quaternion))
            self._require_ok(ret, "quaternion_to_rot_matrix")
            ret = self.robot.rot_matrix_to_rpy(ret[1])
        self._require_ok(ret, "rot_matrix_to_rpy")
        return ret[1]

    def set_tool_id(self, tool_id: int) -> Any:
        with self._sdk_lock:
            ret = self.robot.set_tool_id(int(tool_id))
        self._require_ok(ret, "set_tool_id")
        return self.get_now_tool_data()

    def get_now_tool_data(self) -> Any:
        with self._sdk_lock:
            ret = self.robot.get_tool_id()
            self._require_ok(ret, "get_tool_id")
            ret = self.robot.get_tool_data(ret[1])
        self._require_ok(ret, "get_tool_data")
        return ret[1]

    def reset_do(self, index: int = 2) -> None:
        with self._sdk_lock:
            self._require_ok(
                self.robot.set_digital_output(0, index, 1),
                "set_digital_output",
            )
            time.sleep(0.4)
            self._require_ok(
                self.robot.set_digital_output(0, index, 0),
                "set_digital_output",
            )

    def _enqueue(
        self,
        action: str,
        samples: list[list[float]],
        speed_rad_s: float | None = None,
        acc_rad_s2: float | None = None,
        tol_rad: float = DEFAULT_JOINT_MOVE_TOL_RAD,
    ) -> ServoQueueHandle:
        if self._shutdown_event.is_set():
            raise JakaError("JAKA joint controller is closed")
        self._start_worker()
        job = _ServoJob(
            action=action,
            samples=samples,
            speed_rad_s=speed_rad_s,
            acc_rad_s2=acc_rad_s2,
            tol_rad=tol_rad,
            done=threading.Event(),
        )
        self._job_queue.put(job)
        return ServoQueueHandle(job)

    def _enqueue_stream(
        self,
        action: str,
        samples: Iterable[JointVector],
        speed_rad_s: float | None = None,
        acc_rad_s2: float | None = None,
        tol_rad: float = DEFAULT_JOINT_MOVE_TOL_RAD,
    ) -> ServoQueueHandle:
        if self._shutdown_event.is_set():
            raise JakaError("JAKA joint controller is closed")
        self._start_worker()
        job = _ServoJob(
            action=action,
            samples=None,
            speed_rad_s=speed_rad_s,
            acc_rad_s2=acc_rad_s2,
            tol_rad=tol_rad,
            sample_iter=samples,
            done=threading.Event(),
        )
        self._job_queue.put(job)
        return ServoQueueHandle(job)

    def _start_worker(self) -> None:
        if self._worker_thread is not None and self._worker_thread.is_alive():
            return
        self._shutdown_event.clear()
        self._worker_thread = threading.Thread(
            target=self._servo_worker,
            name="jaka-servo-sender",
            daemon=True,
        )
        self._worker_thread.start()

    def _servo_worker(self) -> None:
        while not self._shutdown_event.is_set():
            job = self._job_queue.get()
            if job is None:
                self._job_queue.task_done()
                break
            try:
                job.result = self._run_motion_job(job)
            except BaseException as exc:
                job.error = exc
                logger.exception(f"JAKA {job.action} job failed: {exc}")
            finally:
                job.done.set()
                self._job_queue.task_done()

    def _run_motion_job(self, job: _ServoJob) -> ServoTrajectoryPlan:
        self._abort_current.clear()
        sent_samples: list[list[float]] = []
        uses_servo_mode = job.action in {"servo_p", "servo_j"}
        with self._sdk_lock:
            self.ready_for_motion()
            if uses_servo_mode:
                self._enable_servo_locked()
            late_cycles = 0
            next_tick: float | None = None
            final_sample: list[float] | None = None

            try:
                for sample in self._iter_job_samples(job):
                    if self._abort_current.is_set():
                        raise JakaError(f"{job.action} job aborted")
                    row = _as_float_vector(sample, 6, f"{job.action} stream sample")
                    if next_tick is not None:
                        late_cycles += _sleep_until(next_tick)
                    sent_at = time.perf_counter()
                    self._send_sample_locked(job, row)
                    sent_samples.append(list(row))
                    final_sample = list(row)
                    next_tick = sent_at + self.servo_period_s

                if final_sample is None:
                    raise ValueError(f"{job.action} stream produced no samples")
                for _ in range(self.hold_cycles):
                    if self._abort_current.is_set():
                        raise JakaError(f"{job.action} job aborted")
                    if next_tick is not None:
                        late_cycles += _sleep_until(next_tick)
                    sent_at = time.perf_counter()
                    self._send_sample_locked(job, final_sample)
                    next_tick = sent_at + self.servo_period_s
            finally:
                if uses_servo_mode:
                    self._disable_servo_locked()

        if late_cycles:
            logger.warning(
                f"JAKA {job.action} stream finished with {late_cycles}/"
                f"{len(sent_samples) + self.hold_cycles} late cycles"
            )
        else:
            logger.debug(
                f"JAKA {job.action} stream finished: samples={len(sent_samples)}"
            )

        return ServoTrajectoryPlan(
            samples=sent_samples,
            duration_s=max(0, len(sent_samples) - 1) * self.servo_period_s,
            period_s=self.servo_period_s,
            action=job.action,
            late_cycles=late_cycles,
        )

    def _iter_job_samples(self, job: _ServoJob):
        if job.sample_iter is not None:
            yield from job.sample_iter
            return
        for sample in job.samples or []:
            yield sample

    def _send_sample_locked(
        self,
        job: _ServoJob,
        sample: Sequence[float],
    ) -> None:
        action = job.action
        if action in {"move_joint", "servo_j"}:
            ret = self._servo_j_locked([float(value) for value in sample])
            self._require_ok(ret, action)
            return

        if action == "servo_p":
            ret = self._servo_p_locked([float(value) for value in sample])
        else:
            raise ValueError(f"Unknown servo action: {action}")
        self._require_ok(ret, action)

    def _servo_p_locked(self, sample: list[float]) -> Any:
        sample = _normalize_cartesian_pose(sample)
        if self._servo_accepts_step_num is False:
            return self.robot.servo_p(sample, ABSOLUTE_MOVE)
        try:
            ret = self.robot.servo_p(sample, ABSOLUTE_MOVE, self.servo_step_num)
        except TypeError:
            self._servo_accepts_step_num = False
            logger.debug("JAKA servo_p binding ignores step_num; using 2 arguments")
            return self.robot.servo_p(sample, ABSOLUTE_MOVE)
        self._servo_accepts_step_num = True
        return ret

    def _servo_j_locked(self, sample: list[float]) -> Any:
        if self._servo_j_accepts_step_num is False:
            return self.robot.servo_j(sample, ABSOLUTE_MOVE)
        try:
            ret = self.robot.servo_j(sample, ABSOLUTE_MOVE, self.servo_step_num)
        except TypeError:
            self._servo_j_accepts_step_num = False
            logger.debug("JAKA servo_j binding ignores step_num; using 2 arguments")
            return self.robot.servo_j(sample, ABSOLUTE_MOVE)
        self._servo_j_accepts_step_num = True
        return ret

    def _joint_move_locked(
        self,
        sample: list[float],
        speed: float,
        acc: float,
        tol: float,
        *,
        block: bool,
    ) -> Any:
        move_extend = getattr(self.robot, "joint_move_extend", None)
        if move_extend is not None:
            try:
                return move_extend(
                    sample,
                    ABSOLUTE_MOVE,
                    bool(block),
                    float(speed),
                    float(acc),
                    float(tol),
                )
            except TypeError:
                logger.debug(
                    "JAKA joint_move_extend binding rejected acc/tol arguments; "
                    "falling back to joint_move"
                )

        move_basic = getattr(self.robot, "joint_move", None)
        if move_basic is None:
            move_basic = getattr(self.robot, "move_joint", None)
        if move_basic is None:
            raise JakaError("JAKA SDK does not provide joint_move/move_joint")
        return move_basic(sample, ABSOLUTE_MOVE, bool(block), float(speed))

    def _enable_servo_locked(self) -> None:
        if self._servo_enabled:
            return
        ret = self._servo_move_enable_locked(True)
        self._require_ok(ret, "servo_move_enable(True)")
        self._servo_enabled = True
        time.sleep(max(self.servo_period_s, 0.02))

    def _disable_servo_locked(self) -> None:
        if not self._servo_enabled:
            return
        ret = self._servo_move_enable_locked(False)
        if self._ok(ret):
            self._servo_enabled = False
            return
        if _ret_code(ret) in (-61, -3):
            logger.debug(f"servo_move_enable(False) returned non-active state: {ret}")
        else:
            logger.warning(f"servo_move_enable(False) returned: {ret}")
        self._servo_enabled = False

    def _servo_move_enable_locked(self, enable: bool) -> Any:
        try:
            return self.robot.servo_move_enable(bool(enable), False)
        except TypeError:
            return self.robot.servo_move_enable(bool(enable))

    def _ensure_ready(self, power_on: bool, enable: bool) -> None:
        status = self.get_status()

        if power_on and status[ROBOT_STATUS_POWERED_ON] == 0:
            with self._sdk_lock:
                self._require_ok(self.robot.power_on(), "power_on")
            self._wait_for_robot_status(ROBOT_STATUS_POWERED_ON, 1)

        if enable and self.get_status()[ROBOT_STATUS_ENABLED] == 0:
            with self._sdk_lock:
                self._require_ok(self.robot.enable_robot(), "enable_robot")
            self._wait_for_robot_status(ROBOT_STATUS_ENABLED, 1)

    def _wait_for_robot_status(
        self,
        status_index: int,
        expected: Any,
        interval_s: float = 0.1,
    ) -> None:
        while self.get_status()[status_index] != expected:
            time.sleep(interval_s)

    def _drain_pending_jobs(self, error: BaseException) -> None:
        while True:
            try:
                job = self._job_queue.get_nowait()
            except queue.Empty:
                return
            if job is None:
                self._job_queue.task_done()
                continue
            job.error = error
            job.done.set()
            self._job_queue.task_done()

    @staticmethod
    def _ok(ret: Any) -> bool:
        return isinstance(ret, (list, tuple)) and len(ret) > 0 and ret[0] == 0

    @classmethod
    def _require_ok(cls, ret: Any, action: str) -> None:
        if not cls._ok(ret):
            raise JakaError(f"{action} failed: {ret}")


def _load_jkrc() -> ModuleType:
    """Load the bundled JAKA SDK for Linux or Windows."""

    global _JKRC_DLL_DIRECTORY_HANDLE
    global _JKRC_MODULE
    global _JKRC_RUNTIME_HANDLE

    with _JKRC_LOAD_LOCK:
        if _JKRC_MODULE is not None:
            return _JKRC_MODULE

        package_path = os.path.dirname(os.path.abspath(__file__))
        if sys.platform == "linux":
            platform_name = "Linux"
            binary_path = os.path.join(package_path, "linux")
            runtime_path = os.path.join(binary_path, "libjakaAPI.so")
            extension_path = os.path.join(binary_path, "jkrc.so")
        elif sys.platform == "win32":
            platform_name = "Windows"
            binary_path = os.path.join(package_path, "win")
            runtime_path = os.path.join(binary_path, "jakaAPI.dll")
            extension_path = os.path.join(binary_path, "jkrc.pyd")
        else:
            raise ImportError(
                "The bundled JAKA SDK supports only 64-bit Linux and Windows; "
                f"current platform is {sys.platform!r}"
            )

        missing_files = [
            path for path in (runtime_path, extension_path) if not os.path.isfile(path)
        ]
        if missing_files:
            names = ", ".join(os.path.basename(path) for path in missing_files)
            raise ImportError(
                f"The bundled JAKA SDK for {platform_name} is incomplete; "
                f"missing: {names} (expected in {binary_path})"
            )

        try:
            if sys.platform == "win32":
                # Since Python 3.8, extension dependencies are resolved only from
                # explicitly registered DLL directories (plus system locations).
                add_dll_directory = getattr(os, "add_dll_directory")
                _JKRC_DLL_DIRECTORY_HANDLE = add_dll_directory(binary_path)
                win_dll = getattr(ctypes, "WinDLL")
                _JKRC_RUNTIME_HANDLE = win_dll(runtime_path)
            else:
                # jkrc.so expects libjakaAPI symbols to be visible globally.
                _JKRC_RUNTIME_HANDLE = ctypes.CDLL(
                    runtime_path,
                    mode=ctypes.RTLD_GLOBAL,
                )
        except (AttributeError, OSError) as exc:
            raise ImportError(
                f"Failed to load the JAKA runtime for {platform_name} "
                f"from {runtime_path}: {exc}"
            ) from exc

        # jkrc is a top-level native extension, so its platform directory must
        # participate in normal module discovery even though this wrapper is a
        # package named ``jaka``.
        if binary_path in sys.path:
            sys.path.remove(binary_path)
        sys.path.insert(0, binary_path)

        try:
            module = importlib.import_module("jkrc")
        except (ImportError, OSError) as exc:
            raise ImportError(
                f"Failed to import the bundled JAKA extension for {platform_name} "
                f"from {extension_path}: {exc}"
            ) from exc

        module_path = os.path.realpath(getattr(module, "__file__", ""))
        if module_path != os.path.realpath(extension_path):
            raise ImportError(
                "A different 'jkrc' module is already loaded from "
                f"{module_path or '<unknown>'}; expected {extension_path}"
            )

        _JKRC_MODULE = module
        return module


def _normalize_angle_rad(angle: float) -> float:
    wrapped = (float(angle) + math.pi) % (2.0 * math.pi) - math.pi
    if wrapped <= -math.pi:
        return math.pi
    return wrapped


def _normalize_cartesian_pose(pose: Sequence[float]) -> list[float]:
    row = [float(value) for value in pose]
    if len(row) >= 6:
        row[3] = _normalize_angle_rad(row[3])
        row[4] = _normalize_angle_rad(row[4])
        row[5] = _normalize_angle_rad(row[5])
    return row


def _as_float_vector(values: Sequence[float], length: int, name: str) -> list[float]:
    row = [float(value) for value in values]
    if len(row) != length:
        raise ValueError(f"{name} must contain exactly {length} values, got {len(row)}")
    if not all(math.isfinite(value) for value in row):
        raise ValueError(f"{name} must contain finite values")
    return row


def _resolve_joint_move_command_limits(
    speed_rad_s: float | None,
    acc_rad_s2: float | None,
    tol_rad: float,
) -> tuple[float, float, float]:
    speed = (
        DEFAULT_JOINT_MOVE_SPEED_RAD_S
        if speed_rad_s is None
        else _positive_float(speed_rad_s, "joint move speed")
    )
    acc = (
        DEFAULT_JOINT_MOVE_ACC_RAD_S2
        if acc_rad_s2 is None
        else _positive_float(acc_rad_s2, "joint move acceleration")
    )
    tol = _non_negative_float(tol_rad, "joint move tolerance")
    return speed, acc, tol


def _positive_float(value: float, name: str) -> float:
    value = float(value)
    if not math.isfinite(value) or value <= 0.0:
        raise ValueError(f"{name} must be a positive finite value")
    return value


def _non_negative_float(value: float, name: str) -> float:
    value = float(value)
    if not math.isfinite(value) or value < 0.0:
        raise ValueError(f"{name} must be a non-negative finite value")
    return value


def _round_vector(values: Sequence[float], digits: int = 4) -> list[float]:
    return [round(float(value), digits) for value in values]


def _ret_code(ret: Any) -> Any:
    if isinstance(ret, (list, tuple)) and ret:
        return ret[0]
    return None


def _sleep_until(deadline: float) -> int:
    remaining = deadline - time.perf_counter()
    if remaining > 0.0:
        time.sleep(remaining)
        return 0
    return 1
